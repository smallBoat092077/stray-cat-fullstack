    @Override
    public void run(ApplicationArguments args) {
        int insertedQuestions = 0;
        for (SeedQuestion q : QUESTIONS) {
            try {
                Integer count = jdbcTemplate.queryForObject(
                        "SELECT COUNT(*) FROM wiki_question WHERE title = ?", Integer.class, q.title());
                if (count != null && count > 0) {
                    continue;
                }
                jdbcTemplate.update(
                        "INSERT INTO wiki_question (category, title, options_json, answer_index, analysis, sort, status, created_at) "
                                + "VALUES (?,?,?,?,?,?,1,NOW())",
                        q.category(), q.title(), JSON.toJSONString(q.options()), q.answerIndex(),
                        q.analysis(), q.sort());
                insertedQuestions++;
            } catch (Exception e) {
                log.warn("百科题目冷启动跳过: title={}, err={}", q.title(), e.getMessage());
            }
        }

        int insertedArticles = 0;
        for (SeedArticle a : ARTICLES) {
            try {
                Integer count = jdbcTemplate.queryForObject(
                        "SELECT COUNT(*) FROM wiki_article WHERE title = ?", Integer.class, a.title());
                if (count != null && count > 0) {
                    continue;
                }
                jdbcTemplate.update(
                        "INSERT INTO wiki_article (title, summary, content, cover_url, category, tags, read_minutes, status, sort, view_count, created_at, updated_at) "
                                + "VALUES (?,?,?,NULL,?,?,?,1,?,0,NOW(),NOW())",
                        a.title(), a.summary(), a.content(), a.category(), a.tags(),
                        a.readMinutes(), a.sort());
                insertedArticles++;
            } catch (Exception e) {
                log.warn("百科文章冷启动跳过: title={}, err={}", a.title(), e.getMessage());
            }
        }
        log.info("猫咪百科冷启动完成：新增 {} 道题、{} 篇文章", insertedQuestions, insertedArticles);
    }
